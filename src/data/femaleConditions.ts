function toLevel(c: FemaleCondition): LevelConfig {
  return {
    id: c.id,
    title: c.title,
    ages: "Women's health",
    cefr: 'Diagnosis',
    tagline: `Describe symptoms and get a diagnosis for ${c.shortName}.`,
    focus: c.focus,
    tutor: {
      name: c.tutorName,
      role: `${c.title} doctor`,
      avatar: c.avatar,
      greeting: `Hello, I am ${c.tutorName}. Report your symptoms. I will name possible diseases, and each new symptom will make the detection more precise.`,
      praise: ['Clear description.', 'Good screening English.', 'That helps the clinic.', 'Well said.', 'Nice and specific.'],
      retry: ['Try a clearer description.', 'Choose another reply.', 'Let’s try again.'],
      next: ['Next chat.', 'Continue.', 'Another case.', 'Ready?'],
    },
    theme: {
      bg: c.bg,
      bg2: c.bg2,
      accent: c.accent,
      accent2: c.accent2,
      ink: c.ink,
      card: '#ffffff',
      bubble: '#ffffff',
      userBubble: '#fff5fa',
    },
  }
}

export const FEMALE_LEVELS: LevelConfig[] = FEMALE_CONDITIONS.map(toLevel)

export const FEMALE_CSV_FILES: Record<LevelId, string> = Object.fromEntries(
  FEMALE_CONDITIONS.map((c) => [c.id, `female/${c.slug}/part-01.csv`]),
) as Record<LevelId, string>

export function getFemaleCondition(id: LevelId): FemaleCondition {
  const hit = FEMALE_CONDITIONS.find((c) => c.id === id)
  if (!hit) throw new Error(`Unknown female condition id: ${id}`)
  return hit
}

export function getFemaleLevel(id: LevelId): LevelConfig {
  const level = FEMALE_LEVELS.find((item) => item.id === id)
  if (!level) throw new Error(`Unknown women's health topic: ${id}`)
  return level
}
