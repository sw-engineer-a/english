function toLevel(c: CancerDef): LevelConfig {
  return {
    id: c.id,
    title: c.title,
    ages: 'Cancer topic',
    cefr: 'Oncology English',
    tagline: `Practice English for ${c.shortName} care talks.`,
    focus: c.focus,
    tutor: {
      name: c.tutorName,
      role: `${c.title} English coach`,
      avatar: c.avatar,
      greeting: `Hello! I am ${c.tutorName}. We will practice English about ${c.shortName}. This is language practice only—not real medical advice or diagnosis.`,
      praise: ['Clear answer!', 'Good oncology English.', 'Well said!', 'That helps a lot.', 'Nice work!'],
      retry: ['Try another reply.', 'Choose a clearer option.', 'Let’s try again.'],
      next: ['Next one!', 'Continue.', 'Another chat!', 'Ready?'],
    },
    theme: {
      bg: c.bg,
      bg2: c.bg2,
      accent: c.accent,
      accent2: c.accent2,
      ink: c.ink,
      card: '#ffffff',
      bubble: '#ffffff',
      userBubble: '#f4f8ff',
    },
  }
}

export const DOCTOR_LEVELS: LevelConfig[] = CANCERS.map(toLevel)

export const DOCTOR_CSV_FILES: Record<LevelId, string> = Object.fromEntries(
  CANCERS.map((c) => [c.id, `${c.slug}/part-01.csv`]),
) as Record<LevelId, string>

/** Folder slug per cancer (one folder per cancer). */
export const DOCTOR_CATEGORY_FOLDERS: Record<LevelId, string> = Object.fromEntries(
  CANCERS.map((c) => [c.id, c.slug]),
) as Record<LevelId, string>

export function getCancer(id: LevelId): CancerDef {
  const hit = CANCERS.find((c) => c.id === id)
  if (!hit) throw new Error(`Unknown cancer id: ${id}`)
  return hit
}

export function getDoctorLevel(id: LevelId): LevelConfig {
  const level = DOCTOR_LEVELS.find((item) => item.id === id)
  if (!level) throw new Error(`Unknown doctor level: ${id}`)
  return level
}
